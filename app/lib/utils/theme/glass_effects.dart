import 'dart:ui' as ui;

import 'package:flutter/widgets.dart';

/// Единственный рубильник realtime-размытий Glass-темы.
///
/// **Зачем.** Настоящее стекло в Glass делает не заливка, а [BackdropFilter]:
/// он читает уже нарисованный кадр под панелью, размывает его и только потом
/// сверху ложится полупрозрачная вуаль. Заливка одна, без blur'а, даёт ровно ту
/// картину, на которую жаловался Игорь: контент под панелью не глушится, а
/// просто просвечивает и накладывается на её собственный текст.
///
/// Плата за это — цена кадра. [BackdropFilter] заставляет движок сохранять и
/// заново фильтровать слой под собой на каждом кадре, и каждая такая панель
/// стоит отдельно. Если на слабом устройстве поедут фреймтаймы, откат должен
/// быть в одну строку и без правки мест использования — для этого и заведён
/// [kGlassRealBlur].
///
/// **Как выключить.** Поставить [kGlassRealBlur] в `false`. Все панели ниже
/// разом теряют realtime-blur и остаются простыми полупрозрачными пилюлями:
/// геометрия, радиусы, тени и заливки не меняются, вид деградирует мягко —
/// стекло становится «плоским», но ничего не ломается и не съезжает.
///
/// **Classic рубильника не касается вовсе**: во всех местах ниже [glassBlur]
/// вызывается только в Glass-ветке, Classic рисуется прежним кодом.
///
/// **Где используется** (список поддерживать актуальным):
///  * `lib/widgets/bottom_nav_bar.dart` — пилюля нижней навигации,
///    radius 34 (капсула), sigma 32.
///  * `lib/pages/home/page.dart` — бар «Ask Omi anything…» на главной,
///    radius 32, sigma 32.
///  * `lib/pages/chat/page.dart` — пилюля композера чата (поле ввода рядом
///    с кнопкой «+»), radius 32, sigma 32. Замер на Pixel: лента сообщений
///    лежит в `Expanded` над композером, в одном `Column` с ним, и под него
///    не заезжает — размывать сейчас нечего, кроме статичной подложки. Blur
///    здесь стоит на будущее (оверлейная раскладка/клавиатурные состояния);
///    если понадобится вернуть проход растеризатора — снимать надо именно
///    этот вызов, а не рубильник целиком.
///  * `lib/pages/settings/settings_drawer.dart` — фон шторки настроек,
///    radius 28 сверху, sigma 38.
///  * `lib/pages/conversation_detail/widgets/summarized_apps_sheet.dart` —
///    панель «Шаблон сводки» на странице разговора, углы прямые (панель
///    приезжает снизу без скруглений), sigma 38.
///  * `lib/pages/conversation_detail/widgets/create_template_bottom_sheet.dart`
///    — панель «Создать свой шаблон», открывается из предыдущей,
///    radius 24 сверху, sigma 38.
///  * `lib/pages/conversations/widgets/move_to_folder_sheet.dart` — панель
///    «Переместить в папку», radius 20 сверху, sigma 38. Вуаль здесь осталась
///    токеном `bgSecondary` — он плотнее `bgPrimary` и поверх блюра хватает.
///
/// Поиски (`search`-панели) сознательно оставлены без realtime-blur — решение
/// Игоря, не недосмотр.
const bool kGlassRealBlur = true;

/// Кладёт под [child] настоящее размытие того, что уже нарисовано ниже.
///
/// [borderRadius] — радиус самой панели: им режется и blur, и содержимое, чтобы
/// размытие не выходило за скруглённые углы. [sigma] — радиус гаусса; ориентир
/// в теме: 48 у фоновой подложки (`GlassBackdrop.blurSigma`), 32 у плавающих
/// пилюль, 38 у шторки настроек, которая должна глушить целую страницу.
///
/// Заливку [child] хелпер не трогает: она остаётся полупрозрачной и при
/// `kGlassRealBlur == false` продолжает работать сама по себе.
Widget glassBlur({required Widget child, required BorderRadius borderRadius, double sigma = 32}) {
  if (!kGlassRealBlur) {
    return ClipRRect(borderRadius: borderRadius, child: child);
  }
  return ClipRRect(
    borderRadius: borderRadius,
    child: BackdropFilter(
      filter: ui.ImageFilter.blur(sigmaX: sigma, sigmaY: sigma),
      child: child,
    ),
  );
}
